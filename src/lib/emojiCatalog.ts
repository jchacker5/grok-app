type RawEmoji = [char: string, name: string, keywords: string[]];

function withCategory(category: string, items: RawEmoji[]): EmojiEntry[] {
  return items.map(([char, name, keywords]) => ({
    char,
    name,
    keywords,
    category,
  }));
}

