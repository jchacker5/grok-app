/**
 * Case-insensitive substring match over name + keywords when `query` is
 * non-empty. Empty query returns the full catalog (optionally scoped to
 * `category`) grouped in catalog order — the panel renders section headers
 * from that same order.
 */
export function filterEmoji(query: string, category?: string): EmojiEntry[] {
  const scoped = category
    ? EMOJI_CATALOG.filter((e) => e.category === category)
    : EMOJI_CATALOG;
  const q = query.trim().toLowerCase();
  if (!q) return scoped;
  return scoped.filter((e) => {
    if (e.name.toLowerCase().includes(q)) return true;
    return e.keywords.some((k) => k.toLowerCase().includes(q));
  });
}
